-- ============================================================
--  CÉREBRO — as notas ("pensamentos") que a Lisa lê, busca, cria e indexa
-- ============================================================
--  A tabela `notes` é o banco de notas do usuário (o "Cérebro"): a Lisa lista, busca e cria
--  notas aqui (src/lib/notes.js) e as indexa junto com os quadros (src/lib/ingest/brain.js).
--
--  Se você já tem um app de notas gravando numa tabela `notes` com estas colunas, não precisa
--  rodar este arquivo. Com BRAIN_USER_ID definido, a Lisa só enxerga as notas desse usuário.
--
--  Pode rodar mais de uma vez. Aplicar: no SQL Editor do Supabase, ou
--    npm run migrar -- db/notas.sql
-- ============================================================

create table if not exists public.notes (
  id          bigint generated by default as identity primary key,
  user_id     uuid,
  subject     text not null,
  moment      text,
  body        text not null default '',
  ref         text,
  created_at  timestamptz not null default now()
);

create index if not exists notes_user_created_idx on public.notes (user_id, created_at desc);

-- A Lisa lê e grava pelo servidor, com a chave de serviço. Com RLS ligado e sem políticas,
-- ninguém de fora (chave anônima) enxerga as notas.
alter table public.notes enable row level security;
